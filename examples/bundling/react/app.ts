export function createTodoApp(): void {
  console.log("\n=== Todo App Example ===");

  const React = require("react");
  const { useState, useEffect } = React;

  function TodoApp() {
    const [todos, setTodos] = useState([
      { id: 1, text: "Learn React", done: false },
      { id: 2, text: "Build app", done: false },
      { id: 3, text: "Deploy", done: false }
    ]);

    const [newTodo, setNewTodo] = useState("");

    const addTodo = () => {
      if (newTodo.trim()) {
        setTodos([
          ...todos,
          { id: Date.now(), text: newTodo, done: false }
        ]);
        setNewTodo("");
      }
    };

    const toggleTodo = (id: number) => {
      setTodos(todos.map(todo =>
        todo.id === id ? { ...todo, done: !todo.done } : todo
      ));
    };

    const removeTodo = (id: number) => {
      setTodos(todos.filter(todo => todo.id !== id));
    };

    return {
      todos,
      newTodo,
      setNewTodo,
      addTodo,
      toggleTodo,
      removeTodo
    };
  }

  const app = TodoApp();
  console.log("✓ Todo app created");
  console.log("  - Todos:", app.todos.length);
  console.log("  - Can add, toggle, remove todos");
}

