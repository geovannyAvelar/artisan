export function exampleBundledPackageUsage(): void {
  console.log("\n=== Bundled Package Usage Example ===");

  // If you have bundled React Router:
  const canUseRouter = (() => {
    try {
      const Router = require("react-router-dom");
      return typeof Router.BrowserRouter === "function";
    } catch {
      return false;
    }
  })();

  if (canUseRouter) {
    console.log("✓ React Router available");

    const Router = require("react-router-dom");

    // Example router setup
    function AppWithRouter() {
      const React = require("react");

      return React.createElement(
        Router.BrowserRouter,
        null,
        React.createElement(
          Router.Routes,
          null,
          React.createElement(Router.Route, {
            path: "/",
            element: React.createElement("h1", null, "Home")
          })
        )
      );
    }

    console.log("✓ Router app component created");
  } else {
    console.log("ℹ React Router not bundled (optional)");
  }
}

