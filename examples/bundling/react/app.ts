function initializeApp(): void {
  const React = require("react");
  const { useState, useEffect } = React;

  // Define a simple functional component
  function Counter() {
    const [count, setCount] = useState(0);

    return React.createElement(
      "div",
      { className: "counter" },
      React.createElement("p", null, `Count: ${count}`),
      React.createElement(
        "button",
        { onClick: () => setCount(count + 1) },
        "Increment"
      ),
      React.createElement(
        "button",
        { onClick: () => setCount(0) },
        "Reset"
      )
    );
  }

  console.log("✓ Counter component created");

  // Example: Class component with lifecycle
  class DataComponent {
    state: any = { data: null, loading: true };

    componentDidMount() {
      // Simulate async data loading
      setTimeout(() => {
        this.state.data = ["Item 1", "Item 2", "Item 3"];
        this.state.loading = false;
      }, 1000);
    }

    render() {
      if (this.state.loading) {
        return React.createElement("div", null, "Loading...");
      }
      return React.createElement(
        "ul",
        null,
        this.state.data.map((item: string) =>
          React.createElement("li", { key: item }, item)
        )
      );
    }
  }

  console.log("✓ DataComponent created");

  // Example: Hooks usage
  demonstrateHooks();
}

