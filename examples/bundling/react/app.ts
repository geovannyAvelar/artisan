// Advanced: React Context for Global State
// ============================================================================

export function demonstrateContextAPI(): void {
  console.log("\n=== React Context API ===");

  const React = require("react");
  const { createContext, useContext, useState } = React;

  // Create a context
  const AppContext = createContext({});

  // Provider component
  function AppProvider({ children }: any) {
    const [user, setUser] = useState({
      name: "John Doe",
      email: "john@example.com",
      role: "admin"
    });

    const value = { user, setUser };

    return React.createElement(
      AppContext.Provider,
      { value },
      children
    );
  }

  // Consumer hook
  function useAppContext() {
    return useContext(AppContext);
  }

  // Example component that uses context
  function UserProfile() {
    const context = useAppContext();

    return React.createElement(
      "div",
      { className: "profile" },
      React.createElement("h1", null, context?.user?.name || "User"),
      React.createElement("p", null, context?.user?.email || "N/A")
    );
  }

  console.log("✓ Context API demonstrated");
  console.log("✓ AppProvider created");
  console.log("✓ useAppContext hook available");
  console.log("✓ UserProfile component created");
}

